#!/usr/bin/env python3
"""Rewrite Package.swift so the given modules come from prebuilt XCFrameworks.

A binary target cannot declare dependencies, so each binary product also gets a thin source
"Deps" target (an empty file) that carries them. `PurseCheckoutPayPal` always stays source:
paypal-ios is a source package without library evolution, so a prebuilt plugin compiled against
it would not be ABI-safe in a merchant's build.

Usage:
  binary-manifest.py path  <xcframeworks-dir> <Module>...        local build (stage 2 of the script)
  binary-manifest.py url   <release-download-base> <Module>=<checksum>...   the released manifest
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "Package.swift"

# What each module needs, beyond the binary itself.
DEPS = {
    "PurseHeadlessCheckout": ['.product(name: "PurseSecureFields", package: "purse-securefields-ios")'],
    "PurseCheckoutApplePay": ['"PurseHeadlessCheckout"', '"PurseHeadlessCheckoutDeps"'],
    "PurseCheckoutKlarna": [
        '"PurseHeadlessCheckout"', '"PurseHeadlessCheckoutDeps"',
        '.product(name: "KlarnaPayments", package: "klarna-mobile-sdk-spm")',
    ],
    "PurseCheckoutPayPal": [
        '"PurseHeadlessCheckout"', '"PurseHeadlessCheckoutDeps"',
        '.product(name: "CorePayments", package: "paypal-ios")',
        '.product(name: "PayPalWebPayments", package: "paypal-ios")',
        '.product(name: "PaymentButtons", package: "paypal-ios")',
    ],
}
ORDER = ["PurseHeadlessCheckout", "PurseCheckoutApplePay", "PurseCheckoutPayPal", "PurseCheckoutKlarna"]


def main() -> None:
    mode, base, *specs = sys.argv[1:]
    binaries = dict(s.split("=", 1) if "=" in s else (s, "") for s in specs)
    assert "PurseHeadlessCheckout" in binaries, "the core is always a binary here"
    source = MANIFEST.read_text()
    packages = re.findall(r"^\s*(\.package\(url:.*\)),?\s*$", source, re.M)

    products, targets = [], []
    for module in ORDER:
        deps = ", ".join(DEPS[module])
        if module in binaries:
            if mode == "path":
                binary = f'.binaryTarget(name: "{module}", path: "{base}/{module}.xcframework")'
            else:
                binary = (f'.binaryTarget(name: "{module}", url: "{base}/{module}.xcframework.zip", '
                          f'checksum: "{binaries[module]}")')
            stub = ROOT / "Sources" / f"{module}Deps" / f"{module}Deps.swift"
            stub.parent.mkdir(parents=True, exist_ok=True)
            stub.write_text(f"// Carries {module}'s dependencies: a binary target cannot declare any.\n")
            products.append(f'.library(name: "{module}", targets: ["{module}", "{module}Deps"])')
            targets += [binary, f'.target(name: "{module}Deps", dependencies: [{deps}])']
        else:
            # Building locally: dynamic, so an archived plugin links the core framework instead of
            # embedding a copy. Released: static, as in the source manifest.
            kind = "type: .dynamic, " if mode == "path" else ""
            products.append(f'.library(name: "{module}", {kind}targets: ["{module}"])')
            targets.append(f'.target(name: "{module}", dependencies: [{deps}], '
                           f'swiftSettings: [.swiftLanguageMode(.v6)])')

    MANIFEST.write_text(
        "// swift-tools-version: 6.0\n"
        "// Generated by scripts/binary-manifest.py for a release — edit the source manifest instead.\n\n"
        "import PackageDescription\n\n"
        "let package = Package(\n"
        '    name: "PurseHeadlessCheckout",\n'
        "    platforms: [.iOS(.v16)],\n"
        "    products: [\n        " + ",\n        ".join(products) + "\n    ],\n"
        "    dependencies: [\n        " + ",\n        ".join(packages) + "\n    ],\n"
        "    targets: [\n        " + ",\n        ".join(targets) + "\n    ]\n"
        ")\n"
    )


if __name__ == "__main__":
    main()
